export function t(key: string, lang: Language = "en") {
  return (
    words[key]?.[lang === "bn" ? 1 : 0] ||
    (/^[A-Z_]+$/.test(key)
      ? words.VALIDATION_ERROR[lang === "bn" ? 1 : 0]
      : key)
  );
}
export function currency(value: string, lang: Language = "en") {
  return new Intl.NumberFormat(lang === "bn" ? "bn-BD" : "en-BD", {
    style: "currency",
    currency: "BDT",
    currencyDisplay: "narrowSymbol",
    maximumFractionDigits: 2,
  }).format(Number(value));
}
export function dateLabel(value: string, lang: Language = "en") {
  return new Intl.DateTimeFormat(lang === "bn" ? "bn-BD" : "en-GB", {
    timeZone: "Asia/Dhaka",
    dateStyle: "full",
  }).format(new Date(value.length === 10 ? value + "T06:00:00Z" : value));
}
